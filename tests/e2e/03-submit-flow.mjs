import { chromium } from './pw.mjs';
import { execSync } from 'node:child_process';
const BASE = 'http://localhost:3333';
const sql = (q) => execSync(`mariadb -N -B ${process.env.E2E_DB || 'mh_test'} -e ${JSON.stringify(q)}`).toString().trim();
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(ok ? 'PASS' : 'FAIL', n, x); };
sql("UPDATE draws SET status='upcoming', nums=NULL, extra=NULL, draw_date=CURDATE()+INTERVAL 2 DAY WHERE draw_no='26/200'");
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const p = await (await b.newContext({ viewport: { width: 420, height: 1000 } })).newPage();
await p.goto(BASE + '/picker');
await p.getByRole('button', { name: 'Quick pick' }).first().click(); await p.waitForTimeout(2500); await p.getByRole('button', { name: 'Add to slip' }).click();
check('guest sees a Submit order button after adding a ticket to the slip', await p.getByRole('button', { name: /Submit order/ }).isVisible());
await p.waitForTimeout(1500);
check('Submit enabled after quick pick', await p.getByRole('button', { name: /Submit order/ }).isEnabled());
await p.getByRole('button', { name: /Submit order/ }).click();
await p.waitForURL('**/login**');
check('guest sent to login with return path', p.url().includes('next=%2Fpicker') || p.url().includes('next=/picker'), p.url());
await p.getByRole('link', { name: 'Create a free account' }).click();
await p.waitForURL('**/register');
const email = `g${Date.now()}@example.com`;
await p.getByLabel('Email').fill(email);
await p.getByLabel('Password').fill('userpass123456');
await p.getByRole('checkbox').check();
await p.getByRole('button', { name: 'Create account' }).click();
await p.waitForURL(/\/account(\?welcome=1)?$/, { timeout: 8000 }).catch(async () => { console.log('STUCK AT', p.url(), (await p.locator('main').innerText()).slice(0, 300)); });
sql(`UPDATE users SET points=1000 WHERE email='${email}'`);
await p.goto(BASE + '/picker');
await p.waitForTimeout(800);
check('ticket kept through sign-up', (await p.locator('[aria-label="Tickets on your slip"] li').count()) === 1);
await p.getByRole('button', { name: /Submit order/ }).click();
await p.waitForURL('**/account/orders/**', { timeout: 15000 }).catch(() => {});
await p.waitForTimeout(1500);
if (!p.url().includes('/picker') && process.env.STAY !== '1') { globalThis.__receiptUrl = p.url(); await p.goto(BASE + '/picker'); }
check('order submitted as pending, 10 points taken', sql(`SELECT CONCAT(o.status,'/',u.points) FROM orders o JOIN users u ON u.id=o.user_id WHERE u.email='${email}'`) === 'pending/990');
check('went to the receipt page', (globalThis.__receiptUrl ?? '').includes('/account/orders/'), globalThis.__receiptUrl);
await p.reload();
check('slip empty after submitting', (await p.locator('[aria-label="Tickets on your slip"] li').count()) === 0);
await p.goto(BASE + '/account');
check('dashboard shows Pending', (await p.locator('body').innerText()).includes('Pending approval'));
await b.close();
console.log(`${pass}/${pass + fail} passed`);
