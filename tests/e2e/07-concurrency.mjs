import { chromium } from './pw.mjs';
import { execSync } from 'node:child_process';
const BASE = 'http://localhost:3333';
const sql = (q) => execSync(`mariadb -N -B ${process.env.E2E_DB || 'mh_test'} -e ${JSON.stringify(q)}`).toString().trim();
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { ok ? pass++ : fail++; console.log(ok ? 'PASS' : 'FAIL', n, x); };
// only draws 26/107 and 26/108 are open, 26/107 first
sql("UPDATE draws SET status='published', nums='1,2,3,4,5,6', extra=7 WHERE status='upcoming'");
sql("DELETE FROM draws WHERE draw_no IN ('26/107','26/108')");
sql("INSERT INTO draws (draw_no, draw_date, status) VALUES ('26/107', CURDATE() + INTERVAL 1 DAY, 'upcoming'), ('26/108', CURDATE() + INTERVAL 3 DAY, 'upcoming')");
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const mkUser = async (i) => {
  const p = await (await b.newContext({ viewport: { width: 420, height: 1200 } })).newPage();
  const email = `n${i}_${Date.now()}@example.com`;
  await p.goto(BASE + '/register');
  await p.getByLabel('Email').fill(email);
  await p.getByLabel('Password').fill('userpass123456');
  await p.getByRole('checkbox').check();
await p.getByRole('button', { name: 'Create account' }).click();
  await p.waitForURL(/\/account(\?welcome=1)?$/);
  sql(`UPDATE users SET points=1000, email_verified=1 WHERE email='${email}'`);
  await p.goto(BASE + '/picker');
  await p.getByRole('button', { name: 'Quick pick' }).first().click();
  await p.waitForTimeout(1600);
  return p;
};
const users = [];
for (let i = 0; i < 3; i++) users.push(await mkUser(i));
// all three submit at the same moment
await Promise.all(users.map((p) => p.getByRole('button', { name: /Submit order/ }).click()));
await Promise.all(users.map((p) => p.waitForURL('**/account/orders/*', { timeout: 20000 }).catch(() => {})));
const nos = await Promise.all(users.map(async (p) => (await p.locator('h1').innerText()).replace('Order No. ', '').trim()));
check('three simultaneous orders all succeeded', nos.every((n) => /^\d{9}$/.test(n)), nos.join(', '));
check('numbers are 26107 + sequence', nos.every((n) => n.startsWith('26107')), nos.join(', '));
check('numbers are all different', new Set(nos).size === 3);
const seqs = nos.map((n) => Number(n.slice(5))).sort((a, c) => a - c);
check('sequence is 1, 2, 3 with no gaps', seqs.join() === '1,2,3', seqs.join());
// next draw: close 26/107, numbering restarts at 0001
sql("UPDATE draws SET status='published', nums='1,2,3,4,5,6', extra=7 WHERE draw_no='26/107'");
await users[0].goto(BASE + '/picker');
await users[0].getByRole('button', { name: 'Quick pick' }).first().click();
await users[0].waitForTimeout(1600);
await users[0].getByRole('button', { name: /Submit order/ }).click();
await users[0].waitForURL('**/account/orders/*');
const n2 = (await users[0].locator('h1').innerText()).replace('Order No. ', '').trim();
check('next draw restarts at 0001', n2 === '261080001', n2);
check('order number shown in My account', (await (async () => { await users[0].goto(BASE + '/account'); return users[0].locator('body').innerText(); })()).includes('Order 261080001'));
check('stored in the database', sql("SELECT COUNT(*) FROM orders WHERE order_no IN ('261080001')") === '1');
// admin search by order number
const admin = await (await b.newContext()).newPage();
await admin.goto(BASE + '/login');
await admin.getByLabel('Email').fill('admin@example.com');
await admin.getByLabel('Password', { exact: true }).fill('adminpass12345');
await admin.getByRole('button', { name: 'Log in' }).click();
await admin.waitForTimeout(1500);
await admin.goto(BASE + '/admin/search?q=261080001');
await admin.waitForTimeout(1000);
check('admin can find an order by its number', (await admin.locator('body').innerText()).includes('Order 261080001'));
await admin.goto(BASE + '/admin/orders?draw=26/108');
await admin.waitForTimeout(1000);
check('admin orders table shows the number', (await admin.locator('body').innerText()).includes('261080001'));
await admin.getByRole('button', { name: 'Approve', exact: true }).first().click();
await admin.waitForTimeout(1200);
check('approve message names the order and the receipt', /Order 261080001 approved\. The buyer can now download the receipt/.test(await admin.locator('body').innerText()));
await users[0].goto(BASE + '/account/orders/' + sql("SELECT id FROM orders WHERE order_no='261080001'"));
await users[0].locator('img[alt^="Receipt for order 261080001"]').waitFor({ timeout: 10000 }).catch(() => {});
check('receipt appears for the buyer after approval', await users[0].locator('img[alt^="Receipt for order 261080001"]').isVisible());
await b.close();
console.log(`${pass}/${pass + fail} passed`);
